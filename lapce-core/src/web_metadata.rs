//! Generated offline packs. These are declarations, not inferred runtime types.
use crate::project_profile::ProjectProfile;
use std::sync::OnceLock;

#[derive(Debug)]
pub struct Symbol {
    pub name: String,
    pub kind: String,
    pub framework: String,
    pub package: String,
    pub version: String,
    pub signature: Option<String>,
    pub qualified_name: Option<String>,
    pub doc_url: String,
}

pub fn symbols() -> &'static [Symbol] {
    static PACK: OnceLock<Vec<Symbol>> = OnceLock::new();
    PACK.get_or_init(|| {
        let values: Vec<serde_json::Value> =
            serde_json::from_str(include_str!("../../metadata/web/symbols.json"))
                .expect("checked generated pack");
        values
            .iter()
            .map(|v| Symbol {
                name: v["name"].as_str().unwrap().to_owned(),
                kind: v["kind"].as_str().unwrap().to_owned(),
                framework: v["framework"].as_str().unwrap().to_owned(),
                package: v["package"].as_str().unwrap().to_owned(),
                version: v["source_version"].as_str().unwrap().to_owned(),
                signature: v["signature"].as_str().map(str::to_owned),
                qualified_name: v["qualified_name"].as_str().map(str::to_owned),
                doc_url: v["doc_url"].as_str().unwrap().to_owned(),
            })
            .collect()
    })
}

/// Packs are exact-version fallbacks, not a promise of latest API compatibility.
/// Unknown WP core version permits an explicitly labelled baseline; mismatched
/// installed Composer package versions are excluded rather than guessed.
pub fn php_symbols(
    profile: &ProjectProfile,
) -> impl Iterator<Item = &'static Symbol> + '_ {
    symbols()
        .iter()
        .filter(move |s| match s.framework.as_str() {
            // PHP standard library (phpstorm-stubs): applies to every PHP file.
            "php" => true,
            "wordpress" => {
                profile.wordpress
                    && profile
                        .wordpress_version
                        .as_ref()
                        .is_none_or(|v| v == &s.version)
                    && profile
                        .packages
                        .get(&s.package)
                        .is_none_or(|v| v.trim_start_matches('v') == s.version)
            }
            "symfony" => profile
                .packages
                .get(&s.package)
                .is_some_and(|v| v.trim_start_matches('v') == s.version),
            _ => false,
        })
}

pub fn php_lists(profile: &ProjectProfile) -> Vec<String> {
    let base = if profile.laravel {
        crate::lexilla::LARAVEL_WORD_LISTS
    } else {
        crate::lexilla::PHP_WORD_LISTS
    };
    let mut lists: Vec<String> = base.iter().map(|s| s.to_string()).collect();
    for symbol in php_symbols(profile) {
        let index = if symbol.kind == "class" { 2 } else { 1 };
        lists[index].push(' ');
        lists[index].push_str(&symbol.name);
    }
    lists
}

/// Flattened key paths of the pinned WordPress JSON schemas (theme.json,
/// block.json). Facts only - key paths, value types and enum values; no
/// schema prose. Generated by scripts/generate-wp-json-schemas.py from the
/// pinned Gutenberg checkout (see metadata/web/manifest.json).
#[derive(Debug, Clone)]
pub struct JsonSchemaEntry {
    pub types: Vec<String>,
    pub values: Vec<String>,
}

#[derive(Debug)]
pub struct JsonSchemaPack {
    pub doc: String,
    entries: Vec<(String, JsonSchemaEntry)>,
}

/// A schema path segment ending in `*` and longer than one char
/// (`when@*`) matches any concrete segment with that prefix (`when@dev`).
fn schema_prefix_match(schema: &str, concrete: &str) -> bool {
    schema
        .strip_suffix('*')
        .is_some_and(|prefix| !prefix.is_empty() && concrete.starts_with(prefix))
}

impl JsonSchemaPack {
    fn matches(schema: &str, concrete: &str) -> bool {
        let mut s = schema.split('.');
        let mut c = concrete.split('.');
        loop {
            match (s.next(), c.next()) {
                (None, None) => return true,
                (Some(a), Some(b)) if a == "*" || a == b || schema_prefix_match(a, b) => {}
                _ => return false,
            }
        }
    }

    /// The entry whose schema path matches `path` segment-wise (`*` covers
    /// any single concrete segment, e.g. a block name or an array item).
    pub fn entry(&self, path: &str) -> Option<&JsonSchemaEntry> {
        self.entries
            .iter()
            .find(|(p, _)| Self::matches(p, path))
            .map(|(_, e)| e)
    }

    /// Child key names offered at `parent`, with their schema entries.
    pub fn children(&self, parent: &str) -> Vec<(String, JsonSchemaEntry)> {
        let depth = if parent.is_empty() {
            0
        } else {
            parent.split('.').count()
        };
        let mut out: Vec<(String, JsonSchemaEntry)> = Vec::new();
        for (path, entry) in &self.entries {
            let segs: Vec<&str> = path.split('.').collect();
            if segs.len() != depth + 1 {
                continue;
            }
            if depth > 0 && !Self::matches(&segs[..segs.len() - 1].join("."), parent) {
                continue;
            }
            let name = segs[segs.len() - 1];
            if !out.iter().any(|(n, _)| n == name) {
                out.push((name.to_string(), entry.clone()));
            }
        }
        out
    }
}

/// The schema pack for a JSON file name (`theme.json` / `block.json`), or
/// None for any other file.
pub fn wp_json_schema(file_name: &str) -> Option<&'static JsonSchemaPack> {
    static PACKS: OnceLock<Vec<(String, JsonSchemaPack)>> = OnceLock::new();
    let packs = PACKS.get_or_init(|| {
        let value: serde_json::Value = serde_json::from_str(include_str!(
            "../../metadata/web/wp-json-schemas.json"
        ))
        .expect("checked generated pack");
        ["theme", "block"]
            .iter()
            .map(|name| (format!("{name}.json"), parse_schema_pack(&value, name)))
            .collect()
    });
    packs.iter().find(|(n, _)| n == file_name).map(|(_, p)| p)
}

fn parse_schema_pack(value: &serde_json::Value, name: &str) -> JsonSchemaPack {
    let doc = value[name]["doc"].as_str().unwrap().to_string();
    let entries = value[name]["entries"]
        .as_object()
        .unwrap()
        .iter()
        .map(|(path, e)| {
            let strings = |key: &str| {
                e[key]
                    .as_array()
                    .map(|a| {
                        a.iter()
                            .filter_map(|v| v.as_str().map(str::to_string))
                            .collect()
                    })
                    .unwrap_or_default()
            };
            (
                path.clone(),
                JsonSchemaEntry {
                    types: strings("types"),
                    values: strings("enum"),
                },
            )
        })
        .collect();
    JsonSchemaPack { doc, entries }
}

/// The Symfony YAML config schema pack (`services` or `routing`; item
/// 445), or None for any other pack name.
pub fn symfony_yaml_schema(pack: &str) -> Option<&'static JsonSchemaPack> {
    static PACKS: OnceLock<Vec<(String, JsonSchemaPack)>> = OnceLock::new();
    let packs = PACKS.get_or_init(|| {
        let value: serde_json::Value = serde_json::from_str(include_str!(
            "../../metadata/web/symfony-yaml-schemas.json"
        ))
        .expect("checked generated pack");
        ["services", "routing"]
            .iter()
            .map(|name| (name.to_string(), parse_schema_pack(&value, name)))
            .collect()
    });
    packs.iter().find(|(n, _)| n == pack).map(|(_, p)| p)
}

/// Where the cursor sits in a JSON document: at a key, or at the value of
/// the path's last key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum JsonPos {
    Key,
    Value,
}

/// Tolerant scan of the document text before the cursor: the object key
/// path the cursor completes at, and whether it sits at a key or a value.
/// Objects inside arrays contribute a `*` segment so schema wildcards
/// (array items, per-block settings) match.
pub fn json_cursor_context(before: &str) -> (Vec<String>, JsonPos) {
    #[derive(Clone, Copy, PartialEq)]
    enum Frame {
        Obj,
        Arr,
    }
    let mut stack: Vec<(Frame, String)> = Vec::new();
    let mut pending: Option<String> = None;
    let mut in_string = false;
    let mut escape = false;
    let mut current = String::new();
    let mut last_was_colon = false;
    let mut string_is_key = false;
    for c in before.chars() {
        if in_string {
            if escape {
                escape = false;
            } else if c == '\\' {
                escape = true;
            } else if c == '"' {
                in_string = false;
                if string_is_key {
                    pending = Some(current.clone());
                }
                current.clear();
            } else {
                current.push(c);
            }
            continue;
        }
        match c {
            '"' => {
                in_string = true;
                current.clear();
                string_is_key = !last_was_colon;
                last_was_colon = false;
            }
            ':' => last_was_colon = true,
            ',' => last_was_colon = false,
            '{' => {
                stack.push((Frame::Obj, pending.take().unwrap_or_default()));
                last_was_colon = false;
            }
            '[' => {
                stack.push((Frame::Arr, pending.take().unwrap_or_default()));
                last_was_colon = false;
            }
            '}' | ']' => {
                stack.pop();
                pending = None;
                last_was_colon = false;
            }
            _ => {}
        }
    }
    let mut path: Vec<String> = Vec::new();
    for (i, (frame, seg)) in stack.iter().enumerate() {
        match frame {
            Frame::Arr => {
                if !seg.is_empty() {
                    path.push(seg.clone());
                }
            }
            Frame::Obj => {
                if i > 0 && stack[i - 1].0 == Frame::Arr && seg.is_empty() {
                    path.push("*".to_string());
                } else if !seg.is_empty() {
                    path.push(seg.clone());
                }
            }
        }
    }
    if (in_string && !string_is_key) || last_was_colon {
        if let Some(key) = pending.take() {
            path.push(key);
        }
        return (path, JsonPos::Value);
    }
    (path, JsonPos::Key)
}

/// The mapping key of a YAML line, tolerating quoted keys; None for
/// scalar lines (sequence items, plain values) without a mapping key.
fn yaml_line_key(content: &str) -> Option<String> {
    let content = content.trim_end();
    if content.is_empty() {
        return None;
    }
    if let Some(q) = content.chars().next().filter(|c| *c == '"' || *c == '\'') {
        let rest = &content[q.len_utf8()..];
        let end = rest.find(q)?;
        let after = rest[end + q.len_utf8()..].trim_start();
        if after.starts_with(':') {
            return Some(rest[..end].to_string());
        }
        return None;
    }
    let colon = content.find(": ").or_else(|| {
        content.ends_with(':').then_some(content.len() - 1)
    })?;
    let key = content[..colon].trim();
    if key.is_empty() {
        return None;
    }
    Some(key.to_string())
}

/// Tolerant scan of the YAML document text before the cursor: the key
/// path the cursor completes at, and whether it sits at a key or a
/// value. Sequence items contribute a `*` segment so schema wildcards
/// match; flow collections and block scalars are out of scope.
pub fn yaml_cursor_context(before: &str) -> (Vec<String>, JsonPos) {
    let mut frames: Vec<(usize, String)> = Vec::new();
    let mut pos = JsonPos::Key;
    let line_count = before.split('\n').count();
    for (idx, line) in before.split('\n').enumerate() {
        let last = idx + 1 == line_count;
        let trimmed = line.trim_start_matches(' ');
        if trimmed.is_empty() || trimmed.starts_with('#') {
            if last {
                let indent = line.len();
                while frames.last().is_some_and(|(i, _)| *i >= indent) {
                    frames.pop();
                }
                pos = JsonPos::Key;
            }
            continue;
        }
        if trimmed.starts_with("---") || trimmed.starts_with("...") {
            continue;
        }
        let base = line.len() - trimmed.len();
        let mut content = trimmed;
        let mut key_indent = base;
        let mut dash = false;
        if let Some(rest) = content.strip_prefix("- ") {
            dash = true;
            key_indent = base + (content.len() - rest.len());
            content = rest;
        } else if content == "-" {
            dash = true;
            content = "";
        }
        if dash {
            let star_indent = base + 1;
            while frames.last().is_some_and(|(i, _)| *i >= star_indent) {
                frames.pop();
            }
            frames.push((star_indent, "*".to_string()));
        }
        match yaml_line_key(content) {
            Some(key) => {
                while frames.last().is_some_and(|(i, _)| *i >= key_indent) {
                    frames.pop();
                }
                frames.push((key_indent, key));
                if last {
                    pos = JsonPos::Value;
                }
            }
            None => {
                if last {
                    while frames.last().is_some_and(|(i, _)| *i >= key_indent) {
                        frames.pop();
                    }
                    pos = JsonPos::Key;
                }
            }
        }
    }
    (frames.into_iter().map(|(_, k)| k).collect(), pos)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn packs_are_separate_versioned_and_nonempty() {
        let wp = ProjectProfile {
            wordpress: true,
            ..Default::default()
        };
        assert!(
            php_symbols(&wp)
                .any(|s| s.name == "add_action" && s.signature.is_some())
        );
        assert!(!php_symbols(&wp).any(|s| s.framework == "twig"));
        let mut sf = ProjectProfile::default();
        sf.packages
            .insert("symfony/console".into(), "v7.3.0".into());
        assert!(php_symbols(&sf).any(|s| s.name == "Command"));
        sf.packages
            .insert("symfony/console".into(), "v6.4.0".into());
        assert_eq!(php_symbols(&sf).filter(|s| s.framework != "php").count(), 0);
        let plain = ProjectProfile::default();
        for name in [
            "strlen", "array_map", "json_encode", "mb_strlen", "DateTime", "Countable",
            // Declared inside `namespace { }` blocks in the stubs (PDO.php, random.php).
            "PDO", "PDOStatement", "rand", "random_bytes", "random_int", "pdo_drivers",
            // Declared inside named braced blocks; qualified_name carries the namespace.
            "Randomizer", "Sqlite", "Mt19937",
        ] {
            assert!(php_symbols(&plain).any(|s| s.name == name && s.framework == "php"), "{name}");
        }
        assert!(php_symbols(&plain).any(|s| s.qualified_name.as_deref() == Some("Random\\Randomizer")));
        assert!(php_symbols(&plain).any(|s| s.qualified_name.as_deref() == Some("Pdo\\Sqlite")));
        assert!(php_lists(&plain)[1].contains(" mb_strlen"));
        assert!(symbols().iter().any(|s| s.framework == "twig"
            && s.kind == "filter"
            && s.name == "upper"));
    }
}

#[cfg(test)]
mod symfony_yaml_tests {
    use super::*;

    #[test]
    fn yaml_cursor_context_tracks_maps_sequences_and_when() {
        let (path, pos) = yaml_cursor_context("services:\n  App\\Foo:\n    aut");
        assert_eq!(path, vec!["services", "App\\Foo"]);
        assert_eq!(pos, JsonPos::Key);
        let (path, pos) =
            yaml_cursor_context("services:\n  App\\Foo:\n    autowire: tr");
        assert_eq!(path, vec!["services", "App\\Foo", "autowire"]);
        assert_eq!(pos, JsonPos::Value);
        let (path, pos) = yaml_cursor_context("imports:\n  - resource: 'a.yaml'\n  - ign");
        assert_eq!(path, vec!["imports", "*"]);
        assert_eq!(pos, JsonPos::Key);
        let (path, pos) = yaml_cursor_context(
            "services:\n  App\\Foo:\n    tags:\n      - name: kernel.event_listener\n        eve",
        );
        assert_eq!(path, vec!["services", "App\\Foo", "tags", "*"]);
        assert_eq!(pos, JsonPos::Key);
        let (path, pos) =
            yaml_cursor_context("when@dev:\n  services:\n    App\\Foo:\n      auto");
        assert_eq!(path, vec!["when@dev", "services", "App\\Foo"]);
        assert_eq!(pos, JsonPos::Key);
        // a fresh indented line below a key completes that key's children
        let (path, pos) = yaml_cursor_context("services:\n  App\\Foo:\n    ");
        assert_eq!(path, vec!["services", "App\\Foo"]);
        assert_eq!(pos, JsonPos::Key);
    }

    #[test]
    fn symfony_yaml_packs_load_and_match() {
        let services = symfony_yaml_schema("services").unwrap();
        let root: Vec<String> =
            services.children("").into_iter().map(|(k, _)| k).collect();
        assert!(root.contains(&"imports".to_string()));
        assert!(root.contains(&"parameters".to_string()));
        assert!(root.contains(&"services".to_string()));
        let def: Vec<String> = services
            .children("services.App\\Foo")
            .into_iter()
            .map(|(k, _)| k)
            .collect();
        assert!(def.contains(&"arguments".to_string()));
        assert!(def.contains(&"autowire".to_string()));
        // the `when@*` prefix wildcard matches concrete environments
        let entry = services
            .entry("when@dev.services.App\\Foo.decoration_on_invalid")
            .unwrap();
        assert!(entry.values.contains(&"exception".to_string()));
        let routing = symfony_yaml_schema("routing").unwrap();
        let keys: Vec<String> =
            routing.children("home").into_iter().map(|(k, _)| k).collect();
        assert!(keys.contains(&"path".to_string()));
        assert!(keys.contains(&"controller".to_string()));
        assert!(symfony_yaml_schema("other").is_none());
    }
}
